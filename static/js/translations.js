function applyTranslations(lang) {
    console.log("Applying translations for language:", lang);
    localStorage.setItem('appLang', lang);
    const elementsToTranslate = document.querySelectorAll('[data-i18n], .translate');
    console.log("Found elements to translate:", elementsToTranslate.length);

    elementsToTranslate.forEach(el => {
        // Handle placeholders first
        if (el.hasAttribute('placeholder')) {
            if (!el.hasAttribute('data-en-placeholder')) {
                el.setAttribute('data-en-placeholder', el.getAttribute('placeholder').trim());
            }
            const pKey = el.getAttribute('data-en-placeholder');
            if (lang === 'te-IN' && translations['te-IN'][pKey]) {
                el.setAttribute('placeholder', translations['te-IN'][pKey]);
            } else {
                el.setAttribute('placeholder', el.getAttribute('data-en-placeholder'));
            }
        }

        // Handle value for input submit/button
        if (el.tagName === 'INPUT' && (el.type === 'submit' || el.type === 'button')) {
            if (!el.hasAttribute('data-en')) el.setAttribute('data-en', el.value.trim());
            const key = el.getAttribute('data-i18n') || el.getAttribute('data-en');
            if (lang === 'te-IN' && translations['te-IN'][key]) {
                el.value = translations['te-IN'][key];
            } else {
                el.value = el.getAttribute('data-en');
            }
            return; // Skip innerText logic
        }

        // Handle select options
        if (el.tagName === 'SELECT') {
            Array.from(el.options).forEach(opt => {
                if (!opt.hasAttribute('data-en')) {
                    opt.setAttribute('data-en', opt.text.trim());
                }
                const optKey = opt.getAttribute('data-en');
                if (lang === 'te-IN' && translations['te-IN'][optKey]) {
                    opt.text = translations['te-IN'][optKey];
                } else {
                    opt.text = opt.getAttribute('data-en');
                }
            });
            return;
        }

        // Skip text node translation for void elements or form inputs
        const skipTextNodeElements = ['INPUT', 'TEXTAREA', 'IMG', 'BR', 'HR'];
        if (skipTextNodeElements.includes(el.tagName.toUpperCase())) {
            return;
        }

        // Handle inner text nodes safely to avoid wiping out child elements like icons
        let textNode = null;
        for (let i = 0; i < el.childNodes.length; i++) {
            if (el.childNodes[i].nodeType === Node.TEXT_NODE && el.childNodes[i].nodeValue.trim().length > 0) {
                textNode = el.childNodes[i];
            }
        }

        if (!textNode && el.childNodes.length === 0) {
            textNode = document.createTextNode(el.innerText || "");
            el.appendChild(textNode);
        }

        if (textNode) {
            if (!el.hasAttribute('data-en')) {
                el.setAttribute('data-en', textNode.nodeValue.trim());
            }
            const key = el.getAttribute('data-i18n') || el.getAttribute('data-en');
            if (lang === 'te-IN' && translations['te-IN'][key]) {
                // Keep leading space if the original text had it, for spacing after icons
                const leadingSpace = textNode.nodeValue.startsWith(' ') ? ' ' : '';
                textNode.nodeValue = leadingSpace + translations['te-IN'][key];
            } else {
                const leadingSpace = textNode.nodeValue.startsWith(' ') ? ' ' : '';
                textNode.nodeValue = leadingSpace + el.getAttribute('data-en');
            }
        }
    });
}

document.addEventListener('DOMContentLoaded', () => {
    // Check saved language
    const savedLang = localStorage.getItem('appLang') || 'en-US';

    // Apply immediately
    applyTranslations(savedLang);

    // Sync global language switcher UI if it exists
    const currentLangLabel = document.getElementById('currentLangLabel');
    if (currentLangLabel) {
        currentLangLabel.innerText = savedLang === 'te-IN' ? 'తెలుగు (Telugu)' : 'English';
    }

    const langSelects = document.querySelectorAll('.global-lang-select');
    langSelects.forEach(el => {
        el.addEventListener('click', function(e) {
            e.preventDefault();
            const lang = this.getAttribute('data-lang');
            applyTranslations(lang);
            
            if (currentLangLabel) {
                currentLangLabel.innerText = lang === 'te-IN' ? 'తెలుగు (Telugu)' : 'English';
            }
            
            // Sync with voiceLanguage if present
            const voiceSelector = document.getElementById('voiceLanguage');
            if (voiceSelector) {
                voiceSelector.value = lang;
            }
        });
    });

    // If there's a voiceLanguage selector on this page, sync it
    const voiceSelector = document.getElementById('voiceLanguage');
    if (voiceSelector) {
        voiceSelector.value = savedLang;
        voiceSelector.addEventListener('change', (e) => {
            console.log("Language selector changed to:", e.target.value);
            applyTranslations(e.target.value);
            if (currentLangLabel) {
                currentLangLabel.innerText = e.target.value === 'te-IN' ? 'తెలుగు (Telugu)' : 'English';
            }
        });
    }
});
